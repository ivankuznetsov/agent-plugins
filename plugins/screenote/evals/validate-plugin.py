#!/usr/bin/env python3
"""Portable, standard-library validation for an isolated Screenote package."""

from __future__ import annotations

import json
import os
from pathlib import Path


PLUGIN_ROOT = Path(__file__).resolve().parents[1]


def fail(message: str) -> None:
    raise SystemExit(f"Screenote validation failed: {message}")


def load_json(relative: str) -> dict:
    path = PLUGIN_ROOT / relative
    if not path.is_file():
        fail(f"missing {relative}")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"invalid {relative}: {exc}")
    if not isinstance(payload, dict):
        fail(f"{relative} must contain a JSON object")
    return payload


def validate_manifests() -> None:
    claude = load_json(".claude-plugin/plugin.json")
    codex = load_json(".codex-plugin/plugin.json")
    package = load_json("package.json")
    openclaw = load_json("openclaw.plugin.json")
    versions = {payload.get("version") for payload in (claude, codex, package, openclaw)}
    if len(versions) != 1 or None in versions:
        fail("manifest versions must agree")
    if claude.get("name") != "screenote" or codex.get("name") != "screenote":
        fail("Claude and Codex manifest names must remain screenote")
    if codex.get("skills") != "./skills/":
        fail("Codex skills must use the canonical ./skills/ tree")
    if any("mcpServers" in payload for payload in (claude, codex)):
        fail("retired transport metadata is forbidden")
    if package.get("pi", {}).get("skills") != ["./pi/skills"]:
        fail("Pi skill root is invalid")
    if openclaw.get("id") != "screenote" or openclaw.get("skills") != ["./openclaw/skills"]:
        fail("OpenClaw metadata is invalid")
    schema = openclaw.get("configSchema")
    if schema != {"type": "object", "additionalProperties": False, "properties": {}}:
        fail("OpenClaw must use the strict empty configuration schema")


def validate_skills() -> None:
    for name in ("screenote", "snapshot", "feedback"):
        path = PLUGIN_ROOT / "skills" / name / "SKILL.md"
        if not path.is_file():
            fail(f"missing canonical skill {name}")
        text = path.read_text(encoding="utf-8")
        if not text.startswith("---\n") or f"\nname: {name}\n" not in text:
            fail(f"invalid frontmatter for {name}")
        if "../../references/cli.md" not in text:
            fail(f"{name} does not load the shared CLI contract")
        if "../../references/workflows.json" not in text:
            fail(f"{name} does not load the shipped workflow contract")
        for platform in ("pi", "openclaw"):
            adapter = PLUGIN_ROOT / platform / "skills" / name / "SKILL.md"
            if not adapter.is_file():
                fail(f"missing {platform} adapter for {name}")
            adapter_text = adapter.read_text(encoding="utf-8")
            if "GENERATED BY scripts/generate-agent-packages.py" not in adapter_text:
                fail(f"{platform} adapter for {name} lacks its generated marker")


def validate_assets() -> None:
    launcher = PLUGIN_ROOT / "scripts" / "screenote-cli.sh"
    if not launcher.is_file() or not os.access(launcher, os.X_OK):
        fail("scripts/screenote-cli.sh must exist and be executable")
    for relative in (
        "scripts/screenote-approved-commands.sh",
        "scripts/screenote_flow.py",
        "references/workflows.json",
    ):
        if not (PLUGIN_ROOT / relative).is_file():
            fail(f"missing {relative}")
    workflows = load_json("references/workflows.json")
    if set(workflows.get("workflows", {})) != {"screenote", "snapshot", "feedback"}:
        fail("workflow contract must cover every canonical Screenote skill")
    if (PLUGIN_ROOT / ".mcp.json").exists():
        fail("retired transport configuration must be removed")
    triggers = json.loads((PLUGIN_ROOT / "evals" / "trigger-eval-set.json").read_text())
    if not isinstance(triggers, list) or not triggers:
        fail("trigger dataset must be a non-empty list")
    allowed = {"screenote", "snapshot", "feedback", None}
    for index, case in enumerate(triggers):
        if not isinstance(case, dict) or not isinstance(case.get("query"), str):
            fail(f"invalid trigger case at index {index}")
        if case.get("should_trigger") not in allowed:
            fail(f"unknown skill in trigger case at index {index}")


def main() -> None:
    validate_manifests()
    validate_skills()
    validate_assets()
    print("Screenote package validation passed")


if __name__ == "__main__":
    main()
