    def test_llm_wiki_cross_skill_names_and_package_paths_resolve_on_every_host(self):
        contract = load_contract(REPO_ROOT)
        plugin = next(plugin for plugin in contract["plugins"] if plugin["name"] == "llm-wiki")
        root = REPO_ROOT / plugin["path"]
        skills = {skill["name"]: skill for skill in plugin["canonical"]["skills"]}
        references = {
            "wiki-plan": ("research", "bootstrap"),
            "research": ("bootstrap",),
            "wiki-status": ("upgrade",),
        }

        for platform in ("claude", "codex", "pi", "openclaw"):
            for source_name, target_names in references.items():
                source = skills[source_name]
                if platform in ("pi", "openclaw"):
                    source_alias = source.get("aliases", {}).get(platform, source_name)
                    source_path = root / platform / "skills" / source_alias / "SKILL.md"
                else:
                    source_path = root / source["path"]
                body = source_path.read_text(encoding="utf-8")

                for target_name in target_names:
                    target = skills[target_name]
                    target_alias = target.get("aliases", {}).get(platform, target_name)
                    if platform in ("pi", "openclaw"):
                        target_path = root / platform / "skills" / target_alias / "SKILL.md"
                    else:
                        target_path = root / target["path"]
                    with self.subTest(
                        platform=platform, source=source_name, target=target_name
                    ):
                        self.assertTrue(target_path.is_file(), target_path)
                        self.assertIn(target_alias, body)

            status = skills["wiki-status"]
            if platform in ("pi", "openclaw"):
                status_alias = status["aliases"][platform]
                status_path = root / platform / "skills" / status_alias / "SKILL.md"
            else:
                status_path = root / status["path"]
            status_body = status_path.read_text(encoding="utf-8")
            self.assertIn("skills/upgrade/scripts/upgrade-project.sh", status_body)
            self.assertNotIn("../upgrade/SKILL.md", status_body)

        self.assertTrue(
            (root / "skills" / "upgrade" / "scripts" / "upgrade-project.sh").is_file()
        )

    def test_packages_survive_isolated_copy(self):
        self.assertEqual([], validate_isolated_packages(REPO_ROOT))

    def test_symlinks_and_path_escapes_are_rejected(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory) / "demo"
            (root / "skills" / "demo").mkdir(parents=True)
            (root / "skills" / "demo" / "SKILL.md").write_text("---\nname: demo\ndescription: demo\n---\n")
            (root / "pi" / "skills" / "demo").mkdir(parents=True)
            adapter = root / "pi" / "skills" / "demo" / "SKILL.md"
            adapter.write_text("[canonical](../../../../outside.md)\n")
            errors = validate_package_tree(root)
            self.assertTrue(any("escapes package" in error for error in errors), errors)
            (root / "bad-link").symlink_to(root / "skills")
            errors = validate_package_tree(root)
            self.assertTrue(any("symlink" in error for error in errors), errors)

    def test_copy_does_not_depend_on_checkout_neighbors(self):
        contract = load_contract(REPO_ROOT)
        with tempfile.TemporaryDirectory() as directory:
            destination = Path(directory) / "package"
            source = REPO_ROOT / contract["plugins"][0]["path"]
            shutil.copytree(source, destination)
            self.assertEqual([], validate_package_tree(destination))


